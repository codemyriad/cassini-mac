"""Generate Cassini/Theme/CassiniTokens.swift from vendored brand/tokens.json."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parent.parent
HEX_RE = re.compile(r'^#[0-9A-Fa-f]{6}(?:[0-9A-Fa-f]{2})?$')


def camel_case(token_id: str) -> str:
    return re.sub(r'-([a-z0-9])', lambda m: m.group(1).upper(), token_id)


def render_swift(root: Path = ROOT) -> str:
    brand_dir = root / 'Cassini/Resources/Brand'
    tokens_path = brand_dir / 'tokens.json'
    upstream_path = brand_dir / 'UPSTREAM.json'

    if not tokens_path.is_file():
        raise ValueError(f'Missing vendored token file: {tokens_path}')
    if not upstream_path.is_file():
        raise ValueError(f'Missing upstream pin file: {upstream_path}')

    pin = json.loads(upstream_path.read_text(encoding='utf-8'))
    if pin.get('repository') != 'cassini-ux' or pin.get('path') != 'brand/tokens.json':
        raise ValueError(f'Unexpected UPSTREAM.json target: {pin}')
    commit = pin.get('commit', '')
    if not re.fullmatch(r'[0-9a-f]{40}', commit):
        raise ValueError(f'Invalid UPSTREAM.json commit SHA: {commit!r}')

    raw_tokens = tokens_path.read_bytes()
    digest = hashlib.sha256(raw_tokens).hexdigest()
    if digest != pin.get('sha256', '').lower():
        raise ValueError(
            f'tokens.json SHA-256 mismatch: got {digest}, UPSTREAM.json has {pin.get("sha256")}'
        )

    doc = json.loads(raw_tokens.decode('utf-8'))
    if doc.get('schema') != 'cassini-ux/brand-tokens@1':
        raise ValueError(f'Unexpected token schema: {doc.get("schema")!r}')
    if doc.get('modes') != ['light', 'dark']:
        raise ValueError(f'Unexpected token modes: {doc.get("modes")!r}')

    version = doc.get('version', '')
    source = doc.get('source', {})
    canvas = source.get('canvas', 'Cassini talk alignment')
    sheet = source.get('sheet', 'project/ui/tokens.css')
    decisions_up_to = source.get('decisionsUpTo', '')

    def collect_active(block: dict[str, dict]) -> list[tuple[str, str, str, str]]:
        out: list[tuple[str, str, str, str]] = []
        seen_swift: set[str] = set()
        for token_id, spec in block.items():
            status = spec.get('status')
            if status not in {'decided', 'placeholder'}:
                continue
            light = spec['light'].upper()
            dark = spec['dark'].upper()
            if not HEX_RE.fullmatch(light) or not HEX_RE.fullmatch(dark):
                raise ValueError(f'Invalid hex in token {token_id!r}: ({light!r}, {dark!r})')
            swift_name = camel_case(token_id)
            if swift_name in seen_swift:
                raise ValueError(f'Duplicate Swift identifier {swift_name!r} for {token_id!r}')
            seen_swift.add(swift_name)
            out.append((token_id, swift_name, light, dark))
        return out

    active_tokens = collect_active(doc.get('tokens', {}))
    active_derived = collect_active(doc.get('derived', {}))
    all_items = active_tokens + active_derived
    if len({s for _, s, _, _ in all_items}) != len(all_items):
        raise ValueError('Collision between tokens and derived Swift identifiers')

    name_pad = max(len(s) for _, s, _, _ in all_items)
    id_pad = max(len(t) for t, _, _, _ in all_items) + 2

    lines: list[str] = [
        '// SPDX-License-Identifier: GPL-3.0-or-later',
        '// Generated by scripts/generate-brand-tokens.py — DO NOT EDIT BY HAND.',
        '// Source: codemyriad/cassini-ux brand/tokens.json',
        f'// Commit: {commit} (version {version}; canvas "{canvas}", {sheet}, decisions up to {decisions_up_to}).',
        'import AppKit',
        'import CryptoKit',
        'import SwiftUI',
        '',
        'enum CassiniTokens {',
        '    static let upstreamRepository = "cassini-ux"',
        '    static let upstreamPath = "brand/tokens.json"',
        f'    static let upstreamCommit = "{commit}"',
        f'    static let upstreamSha256 = "{digest}"',
        '',
        '    struct Entry: Sendable, Equatable {',
        '        let id: String',
        '        let swiftName: String',
        '        let light: String',
        '        let dark: String',
        '',
        '        var lightRGB: UInt32 { CassiniTokens.parseRGB24(light) }',
        '        var darkRGB: UInt32 { CassiniTokens.parseRGB24(dark) }',
        '        var nsColor: NSColor { CassiniTokens.dynamicSRGB(light: light, dark: dark) }',
        '        var color: Color { Color(nsColor: nsColor) }',
        '',
        '        func resolvedNSColor(dark isDark: Bool) -> NSColor {',
        '            CassiniTokens.parseSRGB(isDark ? dark : light)',
        '        }',
        '    }',
        '',
        '    // Active tokens (`status` in {"decided", "placeholder"}).',
    ]

    for token_id, swift_name, light, dark in active_tokens:
        entry_prop = f'{swift_name}Entry'.ljust(name_pad + 5)
        id_lit = f'"{token_id}",'.ljust(id_pad + 1)
        swift_lit = f'"{swift_name}",'.ljust(name_pad + 3)
        light_lit = f'"{light}",'.ljust(12)
        lines.append(
            f'    static let {entry_prop} = Entry(id: {id_lit} swiftName: {swift_lit} light: {light_lit} dark: "{dark}")'
        )

    if active_derived:
        lines.append('')
        lines.append('    // Active derived tokens (`status` in {"decided", "placeholder"}).')
        for token_id, swift_name, light, dark in active_derived:
            entry_prop = f'{swift_name}Entry'.ljust(name_pad + 5)
            id_lit = f'"{token_id}",'.ljust(id_pad + 1)
            swift_lit = f'"{swift_name}",'.ljust(name_pad + 3)
            light_lit = f'"{light}",'.ljust(12)
            lines.append(
                f'    static let {entry_prop} = Entry(id: {id_lit} swiftName: {swift_lit} light: {light_lit} dark: "{dark}")'
            )

    lines.append('')
    lines.append('    static let entries: [Entry] = [')
    for i in range(0, len(active_tokens), 5):
        chunk = ', '.join(f'{s}Entry' for _, s, _, _ in active_tokens[i:i + 5])
        lines.append(f'        {chunk},')
    lines.append('    ]')

    lines.append('')
    if active_derived:
        derived_list = ', '.join(f'{s}Entry' for _, s, _, _ in active_derived)
        lines.append(f'    static let derivedEntries: [Entry] = [{derived_list}]')
    else:
        lines.append('    static let derivedEntries: [Entry] = []')
    lines.append('    static let allEntries: [Entry] = entries + derivedEntries')

    lines.append('')
    lines.append('    enum ns {')
    for _, swift_name, _, _ in all_items:
        prop = swift_name.ljust(name_pad)
        lines.append(f'        static let {prop} = {swift_name}Entry.nsColor')
    lines.append('    }')

    lines.append('')
    for _, swift_name, _, _ in all_items:
        prop = swift_name.ljust(name_pad)
        lines.append(f'    static let {prop} = {swift_name}Entry.color')

    lines.extend([
        '',
        '    static func parseRGB24(_ hex: String) -> UInt32 {',
        '        let digits = hex.hasPrefix("#") ? String(hex.dropFirst()) : hex',
        '        precondition(digits.count == 6 || digits.count == 8, "Invalid token hex: \\(hex)")',
        '        var raw: UInt64 = 0',
        '        let ok = Scanner(string: String(digits.prefix(6))).scanHexInt64(&raw)',
        '        precondition(ok, "Non-hex token: \\(hex)")',
        '        return UInt32(raw & 0xFFFFFF)',
        '    }',
        '',
        '    static func parseSRGB(_ hex: String) -> NSColor {',
        '        let digits = hex.hasPrefix("#") ? String(hex.dropFirst()) : hex',
        '        precondition(digits.count == 6 || digits.count == 8, "Invalid token hex: \\(hex)")',
        '        var raw: UInt64 = 0',
        '        let ok = Scanner(string: digits).scanHexInt64(&raw)',
        '        precondition(ok, "Non-hex token: \\(hex)")',
        '        if digits.count == 6 {',
        '            let r = CGFloat((raw >> 16) & 0xFF) / 255',
        '            let g = CGFloat((raw >> 8) & 0xFF) / 255',
        '            let b = CGFloat(raw & 0xFF) / 255',
        '            return NSColor(srgbRed: r, green: g, blue: b, alpha: 1)',
        '        } else {',
        '            let r = CGFloat((raw >> 24) & 0xFF) / 255',
        '            let g = CGFloat((raw >> 16) & 0xFF) / 255',
        '            let b = CGFloat((raw >> 8) & 0xFF) / 255',
        '            let a = CGFloat(raw & 0xFF) / 255',
        '            return NSColor(srgbRed: r, green: g, blue: b, alpha: a)',
        '        }',
        '    }',
        '',
        '    static func dynamicSRGB(light: String, dark: String) -> NSColor {',
        '        let lightColor = parseSRGB(light)',
        '        let darkColor = parseSRGB(dark)',
        '        return NSColor(name: nil) { appearance in',
        '            appearance.bestMatch(from: [.aqua, .darkAqua]) == .darkAqua ? darkColor : lightColor',
        '        }',
        '    }',
        '',
        '    static func camelCaseName(for tokenID: String) -> String {',
        '        let parts = tokenID.split(separator: "-", omittingEmptySubsequences: false).map(String.init)',
        '        guard let first = parts.first else { return tokenID }',
        '        return first + parts.dropFirst().map { part in',
        '            guard let head = part.first else { return "" }',
        '            return String(head).uppercased() + part.dropFirst()',
        '        }.joined()',
        '    }',
        '',
        '    static func resolvedHex(_ color: NSColor, dark: Bool, includeAlpha: Bool) -> String? {',
        '        guard let appearance = NSAppearance(named: dark ? .darkAqua : .aqua) else { return nil }',
        '        var srgb: NSColor?',
        '        appearance.performAsCurrentDrawingAppearance {',
        '            srgb = color.usingColorSpace(.sRGB)',
        '        }',
        '        guard let resolved = srgb else { return nil }',
        '        func byte(_ c: CGFloat) -> Int { Int((min(1, max(0, c)) * 255).rounded()) }',
        '        let r = byte(resolved.redComponent)',
        '        let g = byte(resolved.greenComponent)',
        '        let b = byte(resolved.blueComponent)',
        '        let a = byte(resolved.alphaComponent)',
        '        return includeAlpha ? String(format: "#%02X%02X%02X%02X", r, g, b, a) : String(format: "#%02X%02X%02X", r, g, b)',
        '    }',
        '',
        '    static func verifySync(',
        '        tokensData: Data,',
        '        upstreamData: Data,',
        '        sheet: [Entry] = entries,',
        '        derivedSheet: [Entry] = derivedEntries',
        '    ) -> Bool {',
        '        struct UpstreamPin: Decodable {',
        '            let repository: String',
        '            let path: String',
        '            let commit: String',
        '            let sha256: String',
        '        }',
        '        struct TokenSpec: Decodable {',
        '            let light: String',
        '            let dark: String',
        '            let status: String',
        '        }',
        '        struct TokenFile: Decodable {',
        '            let schema: String',
        '            let modes: [String]',
        '            let tokens: [String: TokenSpec]',
        '            let derived: [String: TokenSpec]?',
        '        }',
        '        guard let pin = try? JSONDecoder().decode(UpstreamPin.self, from: upstreamData),',
        '              pin.repository == upstreamRepository,',
        '              pin.path == upstreamPath,',
        '              pin.commit == upstreamCommit else { return false }',
        '        let digest = SHA256.hash(data: tokensData).map { String(format: "%02x", $0) }.joined()',
        '        guard digest == pin.sha256.lowercased(),',
        '              digest == upstreamSha256,',
        '              let file = try? JSONDecoder().decode(TokenFile.self, from: tokensData),',
        '              file.schema == "cassini-ux/brand-tokens@1",',
        '              file.modes == ["light", "dark"] else { return false }',
        '',
        '        func matches(_ specs: [String: TokenSpec], against list: [Entry]) -> Bool {',
        '            let active = specs.filter { $0.value.status == "decided" || $0.value.status == "placeholder" }',
        '            let byID = Dictionary(uniqueKeysWithValues: list.map { ($0.id, $0) })',
        '            guard byID.count == list.count, byID.count == active.count else { return false }',
        '            for (id, spec) in active {',
        '                guard let entry = byID[id],',
        '                      entry.swiftName == camelCaseName(for: id) else { return false }',
        '                let wantLight = spec.light.uppercased()',
        '                let wantDark = spec.dark.uppercased()',
        '                guard entry.light.uppercased() == wantLight,',
        '                      entry.dark.uppercased() == wantDark,',
        '                      resolvedHex(entry.nsColor, dark: false, includeAlpha: wantLight.count == 9) == wantLight,',
        '                      resolvedHex(entry.nsColor, dark: true, includeAlpha: wantDark.count == 9) == wantDark else { return false }',
        '            }',
        '            return true',
        '        }',
        '',
        '        return matches(file.tokens, against: sheet) && matches(file.derived ?? [:], against: derivedSheet)',
        '    }',
        '',
        '    #if DEBUG',
        '    static func nativeSelfTest(',
        '        tokensURL: URL? = Bundle.main.url(forResource: "tokens", withExtension: "json", subdirectory: "Brand"),',
        '        upstreamURL: URL? = Bundle.main.url(forResource: "UPSTREAM", withExtension: "json", subdirectory: "Brand")',
        '    ) -> [String: Bool] {',
        '        guard let tokensURL, let upstreamURL,',
        '              let tokensData = try? Data(contentsOf: tokensURL),',
        '              let upstreamData = try? Data(contentsOf: upstreamURL) else {',
        '            return ["brandTokensSynced": false, "brandTokensRejectsDrift": false]',
        '        }',
        '        let synced = entries.count == 53 && verifySync(tokensData: tokensData, upstreamData: upstreamData)',
        '        var driftedLight = entries',
        '        driftedLight[0] = Entry(id: driftedLight[0].id, swiftName: driftedLight[0].swiftName, light: driftedLight[0].dark, dark: driftedLight[0].dark)',
        '        var driftedDark = entries',
        '        driftedDark[9] = Entry(id: driftedDark[9].id, swiftName: driftedDark[9].swiftName, light: driftedDark[9].light, dark: driftedDark[9].light)',
        '        let dropped = Array(entries.dropLast())',
        '        let droppedDerived: [Entry] = []',
        '        let badDigest = Data((String(data: upstreamData, encoding: .utf8) ?? "").replacingOccurrences(of: upstreamCommit, with: String(repeating: "0", count: 40)).utf8)',
        '        let rejectsDrift = !verifySync(tokensData: tokensData, upstreamData: upstreamData, sheet: driftedLight)',
        '            && !verifySync(tokensData: tokensData, upstreamData: upstreamData, sheet: driftedDark)',
        '            && !verifySync(tokensData: tokensData, upstreamData: upstreamData, sheet: dropped)',
        '            && (derivedEntries.isEmpty || !verifySync(tokensData: tokensData, upstreamData: upstreamData, derivedSheet: droppedDerived))',
        '            && !verifySync(tokensData: tokensData, upstreamData: badDigest)',
        '        return ["brandTokensSynced": synced, "brandTokensRejectsDrift": rejectsDrift]',
        '    }',
        '    #endif',
        '}',
        '',
    ])
    return '\n'.join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if CassiniTokens.swift differs from generated output')
    args = parser.parse_args()

    swift_path = ROOT / 'Cassini/Theme/CassiniTokens.swift'
    expected = render_swift(ROOT)
    if args.check:
        if not swift_path.is_file():
            raise SystemExit(f'Missing generated file: {swift_path}')
        actual = swift_path.read_text(encoding='utf-8')
        if actual != expected:
            raise SystemExit(
                f'{swift_path} is out of date with Cassini/Resources/Brand/tokens.json; '
                'run python3 scripts/generate-brand-tokens.py'
            )
        print('CassiniTokens.swift matches generated output byte-for-byte')
        return 0

    swift_path.parent.mkdir(parents=True, exist_ok=True)
    swift_path.write_text(expected, encoding='utf-8')
    print(f'Wrote {swift_path.relative_to(ROOT)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
